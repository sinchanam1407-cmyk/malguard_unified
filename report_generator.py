"""
report_generator.py — Generate human-readable and machine-readable scan reports.

Provides two report formats:
  * Plain-text (``.txt``) — formatted for human review
  * JSON — full structured data for programmatic consumption or archiving

Usage::

    from report_generator import generate_text_report, generate_json_report

    text = generate_text_report(scan_data)
    json_str = generate_json_report(scan_data)
"""

import json
import logging
import os
import re
from datetime import datetime, timezone
from typing import Any

logger = logging.getLogger(__name__)

# Separator used in the text report
_SEP = "=" * 72
_THIN_SEP = "-" * 72

_DISCLAIMER = (
    "DISCLAIMER: This report is generated by an automated analysis tool and is\n"
    "provided for informational purposes only.  It does NOT constitute a legal\n"
    "opinion or guarantee of safety.  A LOW or BENIGN assessment does NOT mean\n"
    "the file is 100% safe.  Always obtain APKs from trusted, verified sources\n"
    "and apply your organisation's software vetting policy before installation."
)


def generate_text_report(scan_data: dict) -> str:
    """
    Generate a multi-section plain-text scan report.

    Parameters
    ----------
    scan_data : dict
        The consolidated scan result dict assembled in ``app.py``.  Expected
        top-level keys: ``filename``, ``file_size``, ``hash_result``,
        ``db_match``, ``integrity_result``, ``signature_result``,
        ``ml_result``, ``assessment``, ``scan_timestamp``.

    Returns
    -------
    str
        Multi-line text report suitable for saving as a ``.txt`` file.
    """
    ts = scan_data.get("scan_timestamp", datetime.now(timezone.utc).isoformat())
    filename = scan_data.get("filename", "unknown")
    file_size = scan_data.get("file_size", 0)
    hash_result = scan_data.get("hash_result") or {}
    db_match = scan_data.get("db_match")
    integrity = scan_data.get("integrity_result") or {}
    signature = scan_data.get("signature_result") or {}
    ml_result = scan_data.get("ml_result") or {}
    assessment = scan_data.get("assessment") or {}

    lines = [
        _SEP,
        "  MalGuard Crypto — Android APK Security Analysis Report",
        _SEP,
        f"  Scan timestamp : {ts}",
        f"  File name      : {filename}",
        f"  File size      : {_fmt_size(file_size)}",
        _SEP,
        "",
        "SECTION 1 — SHA-256 CRYPTOGRAPHIC FINGERPRINT",
        _THIN_SEP,
        f"  SHA-256 : {hash_result.get('sha256', 'N/A')}",
        "",
        "SECTION 2 — HASH DATABASE MATCH",
        _THIN_SEP,
    ]

    if db_match:
        lines += [
            f"  Status         : MATCH FOUND",
            f"  Classification : {db_match.get('classification', 'N/A').upper()}",
            f"  Source         : {db_match.get('source', 'N/A')}",
            f"  Date added     : {db_match.get('date_added', 'N/A')}",
            f"  Description    : {db_match.get('description', 'N/A')}",
        ]
    else:
        lines.append("  Status         : No exact match in the hash database.")

    lines += [
        "",
        "SECTION 3 — FILE INTEGRITY VERIFICATION",
        _THIN_SEP,
        f"  Status         : {integrity.get('status', 'N/A').upper()}",
        f"  Stored hash    : {integrity.get('stored_hash') or 'N/A'}",
        f"  Current hash   : {integrity.get('current_hash') or 'N/A'}",
        f"  Message        : {integrity.get('message', 'N/A')}",
        "",
        "SECTION 4 — DIGITAL SIGNATURE VERIFICATION",
        _THIN_SEP,
        f"  Status         : {signature.get('status', 'N/A').upper()}",
        f"  Tool used      : {signature.get('tool_used', 'N/A')}",
        f"  Message        : {signature.get('message', 'N/A')}",
    ]

    cert_info = (signature.get("certificate_info") or "").strip()
    if cert_info:
        lines += [
            "  Certificate info (excerpt):",
        ]
        for cert_line in cert_info.splitlines()[:10]:
            lines.append(f"    {cert_line}")

    lines += [
        "",
        "SECTION 5 — MACHINE LEARNING PREDICTION",
        _THIN_SEP,
        f"  Model          : {ml_result.get('model_name', 'N/A')}",
        f"  Prediction     : {ml_result.get('prediction', 'N/A').upper()}",
    ]

    conf = ml_result.get("confidence")
    lines.append(
        f"  Confidence     : {conf:.1%}" if conf is not None else "  Confidence     : N/A"
    )
    lines.append(f"  Features used  : {ml_result.get('feature_count', 'N/A')}")
    if ml_result.get("error"):
        lines.append(f"  Error          : {ml_result['error']}")

    lines += [
        "",
        "SECTION 6 — OVERALL ASSESSMENT",
        _THIN_SEP,
        f"  Risk level     : {assessment.get('overall_risk', 'N/A')}",
        f"  Risk score     : {assessment.get('risk_score', 'N/A')} / 100",
        "",
        "  Findings:",
    ]
    for finding in assessment.get("findings", []):
        lines.append(f"    • {finding}")

    lines += [
        "",
        "  Recommendation:",
        f"    {assessment.get('recommendation', 'N/A')}",
        "",
        _SEP,
        "DISCLAIMER",
        _THIN_SEP,
    ]
    for disclaimer_line in _DISCLAIMER.splitlines():
        lines.append(f"  {disclaimer_line}")
    lines.append(_SEP)

    return "\n".join(lines)


def generate_json_report(scan_data: dict) -> str:
    """
    Serialise the full scan data dictionary as a pretty-printed JSON string.

    Parameters
    ----------
    scan_data : dict
        The consolidated scan result dict.

    Returns
    -------
    str
        Pretty-printed JSON string (indent=2).
    """
    try:
        return json.dumps(scan_data, indent=2, default=str)
    except Exception as exc:
        logger.error("generate_json_report: serialisation error: %s", exc)
        return json.dumps({"error": str(exc)}, indent=2)


def get_report_filename(original_name: str, ext: str = "txt") -> str:
    """
    Build a timestamped report filename.

    Parameters
    ----------
    original_name : str
        Original APK filename (e.g., ``"my_app.apk"``).
    ext : str
        File extension for the report (default ``"txt"``).

    Returns
    -------
    str
        Filename like ``scan_report_my_app_20251028_143022.txt``.
    """
    stem = os.path.splitext(os.path.basename(original_name))[0]
    # Sanitise: replace anything that's not alphanumeric, dash, or underscore
    stem = re.sub(r"[^\w\-]", "_", stem)
    timestamp = datetime.now().strftime("%Y%m%d_%H%M%S")
    return f"scan_report_{stem}_{timestamp}.{ext}"


# ── Internal helpers ───────────────────────────────────────────────────────────

def _fmt_size(size_bytes: Any) -> str:
    """Format a byte count as a human-readable string."""
    try:
        n = int(size_bytes)
    except (TypeError, ValueError):
        return "N/A"
    if n < 1024:
        return f"{n} B"
    if n < 1024 ** 2:
        return f"{n / 1024:.1f} KB"
    if n < 1024 ** 3:
        return f"{n / 1024 ** 2:.1f} MB"
    return f"{n / 1024 ** 3:.2f} GB"
